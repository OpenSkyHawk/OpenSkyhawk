# OpenSkyhawk — bundle the Gateway's PanelBridge image into SimGateway (#367). PlatformIO runs it
# before the build (a PRE script: only those may add sources); it builds the bridge project named in this env, and compiles its firmware.bin
# into the Gateway firmware as `osh_bundled_bridge` / `osh_bundled_bridge_len` (Uploader.cpp's weak
# defaults otherwise). One Gateway release then always carries the matching cockpit side, and the
# uploader can flash it with nothing staged (UPL_FLASH target 0).
#
#   extra_scripts = pre:../../shared/bundle_bridge.py
#   custom_bridge_project = ../PanelBridge     ; the bridge project, from this one
#   custom_bridge_env     = PanelBridge        ; its env
Import("env")  # noqa: F821 — provided by PlatformIO
import os
import subprocess

project = env.GetProjectOption("custom_bridge_project", "")
if project:
    project = os.path.normpath(os.path.join(env.subst("$PROJECT_DIR"), project))
    bridge_env = env.GetProjectOption("custom_bridge_env", "")
    cmd = [env.subst("$PYTHONEXE"), "-m", "platformio", "run", "-d", project] + (["-e", bridge_env] if bridge_env else [])
    if subprocess.call(cmd, stdout=subprocess.DEVNULL) != 0:
        env.Exit(f"bundle_bridge: building {project} failed — run it on its own to see why")
    image = open(os.path.join(project, ".pio", "build", bridge_env or "", "firmware.bin"), "rb").read()

    out_dir = os.path.join(env.subst("$BUILD_DIR"), "bundle_src")
    os.makedirs(out_dir, exist_ok=True)
    body = ",".join(str(b) for b in image)
    src = ("// Generated by Firmware/shared/bundle_bridge.py — the bridge image this Gateway firmware carries.\n"
           "#include <stdint.h>\n"
           f'extern "C" __attribute__((used)) const uint8_t osh_bundled_bridge[{len(image)}] = {{{body}}};\n'
           f'extern "C" __attribute__((used)) const uint32_t osh_bundled_bridge_len = {len(image)};\n')
    path = os.path.join(out_dir, "bundled_bridge.cpp")
    if not os.path.exists(path) or open(path).read() != src:   # unchanged → no rebuild
        open(path, "w").write(src)
    env.BuildSources(os.path.join("$BUILD_DIR", "bundle_obj"), out_dir)
    print(f"bundle_bridge: {os.path.relpath(project)} · {len(image)} B")
